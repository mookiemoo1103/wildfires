#!/usr/bin/env python3
"""Generate a compact, GRLevelX-compatible active wildfire placefile."""

import json
import pathlib
import urllib.parse
import urllib.request
from datetime import datetime, timezone
from zoneinfo import ZoneInfo

INCIDENT_QUERY = (
    "https://services3.arcgis.com/T4QMspbfLg3qTGWY/arcgis/rest/services/"
    "WFIGS_Incident_Locations_Current/FeatureServer/0/query"
)
OUTPUT = pathlib.Path("active_wildfires.txt")
ICON_URL = (
    "https://raw.githubusercontent.com/mookiemoo1103/wildfires/"
    "main/assets/fire_icon.png"
)
LOCAL_TZ = ZoneInfo("America/Chicago")
USER_AGENT = "AguaceroWx-Wildfire-Placefile/2.0"


def fetch_incidents():
    where = (
        "IncidentTypeCategory = 'WF' "
        "AND ContainmentDateTime IS NULL "
        "AND ControlDateTime IS NULL "
        "AND FireOutDateTime IS NULL "
        "AND (PercentContained IS NULL OR PercentContained < 100)"
    )
    params = {
        "where": where,
        "outFields": (
            "IncidentName,FireDiscoveryDateTime,IncidentSize,"
            "PercentContained,ContainmentDateTime,ControlDateTime,"
            "FireOutDateTime,IncidentTypeCategory,POOState,POOCounty"
        ),
        "returnGeometry": "true",
        "outSR": "4326",
        "f": "json",
        "resultRecordCount": 2000,
    }
    url = INCIDENT_QUERY + "?" + urllib.parse.urlencode(params)
    request = urllib.request.Request(
        url, headers={"User-Agent": USER_AGENT}
    )
    with urllib.request.urlopen(request, timeout=60) as response:
        payload = json.loads(response.read().decode("utf-8"))
    if "error" in payload:
        raise RuntimeError(f"NIFC/ArcGIS error: {payload['error']}")

    results = []
    for feature in payload.get("features", []):
        attrs = feature.get("attributes") or {}
        geom = feature.get("geometry") or {}
        lon, lat = geom.get("x"), geom.get("y")
        if lat is None or lon is None:
            continue
        if attrs.get("IncidentTypeCategory") != "WF":
            continue
        if any(attrs.get(field) for field in (
            "ContainmentDateTime", "ControlDateTime", "FireOutDateTime"
        )):
            continue

        containment = attrs.get("PercentContained")
        try:
            if containment is not None and float(containment) >= 100:
                continue
        except (TypeError, ValueError):
            containment = None

        discovery = attrs.get("FireDiscoveryDateTime")
        try:
            if discovery:
                started = datetime.fromtimestamp(
                    int(discovery) / 1000, timezone.utc
                ).astimezone(LOCAL_TZ).strftime("%b %d, %Y")
            else:
                started = "Not reported"
        except (TypeError, ValueError, OverflowError):
            started = "Not reported"

        acres = attrs.get("IncidentSize")
        try:
            acres_text = f"{float(acres):,.0f}" if acres is not None else "Not reported"
        except (TypeError, ValueError):
            acres_text = "Not reported"

        try:
            containment_text = (
                f"{float(containment):.1f}%" if containment is not None
                else "Not reported"
            )
        except (TypeError, ValueError):
            containment_text = "Not reported"

        county = attrs.get("POOCounty") or ""
        state = attrs.get("POOState") or ""
        location = ", ".join(part for part in (county, state) if part)
        if not location:
            location = "United States"

        results.append({
            "name": str(attrs.get("IncidentName") or "Unnamed Wildfire"),
            "lat": float(lat),
            "lon": float(lon),
            "started": started,
            "acres": acres_text,
            "containment": containment_text,
            "location": location,
        })
    return results


def safe_hover_text(fire):
    text = (
        f"{fire['name']} | {fire['location']} | "
        f"Started: {fire['started']} | Acres: {fire['acres']} | "
        f"Containment: {fire['containment']}"
    )
    # GR placefile hover text is quoted; remove characters that can break it.
    return text.replace('"', "'").replace("\r", " ").replace("\n", " ")


def main():
    fires = fetch_incidents()
    lines = [
        "; Active wildfires - NIFC WFIGS current incident feed",
        "; US coverage. Generated by GitHub Actions.",
        "Title: Active Wildfires - United States",
        "RefreshSeconds: 10",
        'Font: 1, 12, 1, "Arial"',
        f'IconFile: 1, 128, 128, 64, 64, "{ICON_URL}"',
    ]

    # Correct GRLevelX Icon syntax:
    # Icon: latitude, longitude, angle, icon-file-number, icon-number, hover text
    for fire in fires:
        lines.append(
            f'Icon: {fire["lat"]:.5f},{fire["lon"]:.5f},0,1,1,'
            f'"{safe_hover_text(fire)}"'
        )

    lines.extend([
        f"; Active wildfire incidents plotted: {len(fires)}",
        "; Source: NIFC WFIGS. Reported values may lag field conditions.",
    ])
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Generated {OUTPUT} with {len(fires)} active wildfire icons.")


if __name__ == "__main__":
    main()
